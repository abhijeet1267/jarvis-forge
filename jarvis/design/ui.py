"""UI concept generator (v1.2).

Produces a **real, self-contained HTML mockup** — one file, inline CSS, no
external requests. It renders in a browser as a static layout to react to, which
is what a UI concept is for.

It is explicitly a *wireframe*, and the output says so. JARVIS does not claim
the layout is a finished design.
"""

from __future__ import annotations

from typing import Any, Dict, List
from xml.sax.saxutils import escape

FONT_STACK = "ui-sans-serif, -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif"

#: Section types understood by the generator.
KNOWN_SECTIONS = {"header", "nav", "hero", "cards", "form", "table", "footer", "sidebar"}

DEFAULT_SECTIONS = ["header", "nav", "hero", "cards", "footer"]


def _parse_sections(spec: str) -> List[str]:
    requested = [s.strip().lower() for s in (spec or "").split(",") if s.strip()]
    return requested or list(DEFAULT_SECTIONS)


def _block(name: str, title: str) -> str:
    builders = {
        "header": (
            '  <header class="bar">\n'
            f'    <div class="brand">{escape(title)}</div>\n'
            '    <nav class="inline">\n'
            '      <span>Home</span><span>Docs</span><span>Settings</span>\n'
            '    </nav>\n'
            '  </header>'
        ),
        "nav": (
            '  <nav class="sidebar">\n'
            '    <div class="item active">Overview</div>\n'
            '    <div class="item">Projects</div>\n'
            '    <div class="item">Memory</div>\n'
            '    <div class="item">Devices</div>\n'
            '  </nav>'
        ),
        "hero": (
            '  <section class="hero">\n'
            f'    <h1>{escape(title)}</h1>\n'
            '    <p>A short sentence describing what this screen is for.</p>\n'
            '    <div class="actions"><button class="primary">Get started</button>'
            '<button class="ghost">Learn more</button></div>\n'
            '  </section>'
        ),
        "cards": (
            '  <section class="cards">\n'
            '    <div class="card"><h3>Card one</h3><p>Summary text.</p></div>\n'
            '    <div class="card"><h3>Card two</h3><p>Summary text.</p></div>\n'
            '    <div class="card"><h3>Card three</h3><p>Summary text.</p></div>\n'
            '  </section>'
        ),
        "form": (
            '  <section class="panel">\n'
            '    <h3>Details</h3>\n'
            '    <label>Name<input placeholder="Value"/></label>\n'
            '    <label>Email<input placeholder="name@example.com"/></label>\n'
            '    <button class="primary">Save</button>\n'
            '  </section>'
        ),
        "table": (
            '  <section class="panel">\n'
            '    <h3>Records</h3>\n'
            '    <table>\n'
            '      <thead><tr><th>Name</th><th>Status</th><th>Updated</th></tr></thead>\n'
            '      <tbody>\n'
            '        <tr><td>Item one</td><td>Active</td><td>Today</td></tr>\n'
            '        <tr><td>Item two</td><td>Paused</td><td>Yesterday</td></tr>\n'
            '      </tbody>\n'
            '    </table>\n'
            '  </section>'
        ),
        "sidebar": (
            '  <aside class="aside">\n'
            '    <h3>Context</h3>\n'
            '    <p>Related information appears here.</p>\n'
            '  </aside>'
        ),
        "footer": (
            '  <footer class="foot">\n'
            '    <span>Wireframe — generated by JARVIS for discussion.</span>\n'
            '  </footer>'
        ),
    }
    return builders.get(name, "")


def ui_concept(title: str, sections: str = "", notes: str = "") -> Dict[str, Any]:
    """Build a self-contained HTML wireframe."""
    if not title:
        return {"ok": False, "error": "I need a title for the concept."}

    requested = _parse_sections(sections)
    unknown = [s for s in requested if s not in KNOWN_SECTIONS]
    known = [s for s in requested if s in KNOWN_SECTIONS] or list(DEFAULT_SECTIONS)

    blocks = "\n".join(_block(name, title) for name in known if _block(name, title))
    note_block = (
        f'    <p class="note">{escape(notes)}</p>\n' if notes else ""
    )

    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>{escape(title)}</title>
<style>
  :root {{ color-scheme: light; }}
  * {{ box-sizing: border-box; }}
  body {{ margin: 0; font-family: {FONT_STACK}; background: #f6f7f9; color: #1f2328; }}
  .wrap {{ max-width: 960px; margin: 0 auto; padding: 24px; }}
  .bar {{ display: flex; align-items: center; justify-content: space-between; padding: 14px 20px;
          background: #fff; border: 1px solid #d8dce2; border-radius: 10px; }}
  .brand {{ font-weight: 600; }}
  .inline span {{ margin-left: 16px; color: #5b6169; font-size: 14px; }}
  .sidebar {{ display: flex; gap: 8px; margin: 16px 0; flex-wrap: wrap; }}
  .item {{ padding: 8px 14px; background: #fff; border: 1px solid #d8dce2; border-radius: 999px;
           font-size: 14px; color: #5b6169; }}
  .item.active {{ background: #e7f0fe; border-color: #2f6fdb; color: #1f2328; }}
  .hero {{ background: #fff; border: 1px solid #d8dce2; border-radius: 12px; padding: 28px; margin-bottom: 16px; }}
  .hero h1 {{ margin: 0 0 8px; font-size: 26px; }}
  .hero p {{ margin: 0 0 16px; color: #5b6169; }}
  .actions {{ display: flex; gap: 10px; }}
  button {{ font: inherit; padding: 9px 16px; border-radius: 8px; cursor: pointer; }}
  .primary {{ background: #2f6fdb; color: #fff; border: 1px solid #2f6fdb; }}
  .ghost {{ background: #fff; color: #1f2328; border: 1px solid #c9ced6; }}
  .cards {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(200px, 1fr)); gap: 14px; }}
  .card, .panel, .aside {{ background: #fff; border: 1px solid #d8dce2; border-radius: 12px; padding: 18px; }}
  .card h3, .panel h3, .aside h3 {{ margin: 0 0 8px; font-size: 15px; }}
  .card p, .aside p {{ margin: 0; color: #5b6169; font-size: 14px; }}
  .panel, .aside {{ margin-top: 16px; }}
  label {{ display: block; margin-bottom: 12px; font-size: 14px; color: #5b6169; }}
  input {{ display: block; width: 100%; margin-top: 4px; padding: 8px 10px; font: inherit;
           border: 1px solid #c9ced6; border-radius: 8px; }}
  table {{ width: 100%; border-collapse: collapse; font-size: 14px; }}
  th, td {{ text-align: left; padding: 8px 6px; border-bottom: 1px solid #e6e9ee; }}
  th {{ color: #5b6169; font-weight: 500; }}
  .foot {{ margin-top: 20px; color: #5b6169; font-size: 13px; }}
  .note {{ margin-top: 12px; padding: 12px 14px; background: #fdf0dc; border-left: 3px solid #9a6700;
           border-radius: 6px; font-size: 14px; }}
  .wireframe-note {{ margin-top: 18px; color: #5b6169; font-size: 12px; font-style: italic; }}
</style>
</head>
<body>
  <div class="wrap">
{blocks}
{note_block}    <p class="wireframe-note">Wireframe — generated by JARVIS to react to, not a finished design.</p>
  </div>
</body>
</html>
"""

    return {
        "ok": True,
        "html": html,
        "sections": known,
        "unknown": unknown,
        "problems": [f"unknown section {u!r}" for u in unknown],
    }
