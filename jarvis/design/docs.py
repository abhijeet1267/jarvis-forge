"""Documentation generator (v1.2).

Produces **real Markdown**. Sections are laid out with placeholders, and the
document says plainly that the body needs filling in — a document that looks
complete but is empty is worse than one that admits it is a skeleton.
"""

from __future__ import annotations

from typing import Any, Dict, List

DEFAULT_DOC_SECTIONS = ["Overview", "Architecture", "Usage", "Configuration", "Troubleshooting"]


def documentation(title: str, sections: str = "", audience: str = "") -> Dict[str, Any]:
    """Build a Markdown document skeleton."""
    if not title:
        return {"ok": False, "error": "I need a title for the document."}

    names = [s.strip() for s in (sections or "").split(",") if s.strip()] or list(DEFAULT_DOC_SECTIONS)

    lines = [f"# {title}", ""]
    if audience:
        lines += [f"*Audience: {audience}*", ""]
    lines += [
        "> This is a generated outline. Each section below needs its content filled in;",
        "> nothing here was invented on your behalf.",
        "",
        "## Table of contents",
        "",
    ]
    for name in names:
        anchor = name.lower().replace(" ", "-")
        lines.append(f"- [{name}](#{anchor})")
    lines.append("")

    for name in names:
        lines += [f"## {name}", "", "_To be written._", ""]

    lines += [
        "---",
        "",
        f"_Generated by JARVIS Forge as a documentation skeleton for {title}._",
    ]

    return {
        "ok": True,
        "markdown": "\n".join(lines),
        "sections": names,
        "problems": [],
    }
